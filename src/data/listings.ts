export function formatListingPrice(price: number): string {
  if (price === 0) {
    return content.freePriceLabel;
  }

  return new Intl.NumberFormat('ru-RU', {
    style: 'currency',
    currency: 'RUB',
    maximumFractionDigits: 0,
  }).format(price);
}

